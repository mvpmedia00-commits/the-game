// Lists every spoken line in the game with the voice file name it plays from.
// Run from the repo root:  node tools/voice-lines.mjs   -> writes assets/voices/LINES.md
// Re-run after changing dialogue: a changed line gets a new file name (old recordings keep working for unchanged lines).
import fs from 'node:fs';
import { voiceId, SPEAKERS } from '../world/lib/audio.js';
import { STORY, FREELANCE, RUBY_STUDIO } from '../world/lib/story.js';

const rows = new Map(); // id -> { who, text, where, phone }
const add = (who, text, where, phone = false) => { if (who === 'Sign' || !text) return; const id = voiceId(who, text); if (!rows.has(id)) rows.set(id, { id, who, text, where, phone: phone && who !== 'MVP' }); };
for (const m of STORY) {
  for (const [w, t] of m.intro || []) add(w, t, `${m.title} · intro${m.giver === 'phone' ? ' (phone call)' : ''}`, m.giver === 'phone');
  for (const [w, t] of m.outro || []) add(w, t, `${m.title} · ending`);
  for (const st of m.steps) if (st.c) for (const o of st.c.options) for (const [w, t] of o.reply || []) add(w, t, `${m.title} · choice "${o.label}"`);
  if (m.choice) for (const o of m.choice.options) for (const [w, t] of o.reply || []) add(w, t, `${m.title} · choice "${o.label}"`);
}
for (const t of [...RUBY_STUDIO.chat, RUBY_STUDIO.prep, RUBY_STUDIO.prepped, RUBY_STUDIO.brk]) add('Ruby Monroe', t, 'MVP Studios · talking to Ruby');
for (const name of FREELANCE) add(name, 'Love these. I am tagging MVP Media on everything.', 'Photo gig · ending');
// lines written straight into the game code: ['Speaker', 'line'] (both sides of a ? : are listed)
const known = new Set([...SPEAKERS, ...FREELANCE]);
for (const f of ['world/main.js', 'world/lib/district.js']) {
  const src = fs.readFileSync(f, 'utf8'), re = /\[\s*'([A-Z][A-Za-z .]+)'\s*,/g; let m;
  while ((m = re.exec(src))) {
    if (!known.has(m[1])) continue;
    const rest = src.slice(re.lastIndex, src.indexOf(']', re.lastIndex));
    for (const q of rest.matchAll(/'((?:[^'\\]|\\.)*)'/g)) if (/\s/.test(q[1])) add(m[1], q[1].replace(/\\'/g, "'"), 'Around town');
  }
}
const by = {}; for (const r of rows.values()) (by[r.who] ||= []).push(r);
let md = `# Voice lines\n\nGenerated by \`node tools/voice-lines.mjs\`. ${rows.size} lines. Record a line, save it as an **.mp3** with the exact file name below, and put it in \`assets/voices/\`. Lines without a file use the computer voice. See README.md in this folder.\n\n`;
for (const who of Object.keys(by).sort((a, b) => (a === 'MVP' ? -1 : b === 'MVP' ? 1 : a.localeCompare(b)))) {
  md += `## ${who} (${by[who].length})\n\n| File | Line | Where |\n|---|---|---|\n`;
  for (const r of by[who]) md += `| \`${r.id}.mp3\` | ${r.text.replace(/\|/g, '\\|')} | ${r.where}${r.phone ? ' 📞' : ''} |\n`;
  md += '\n';
}
fs.writeFileSync('assets/voices/LINES.md', md);
console.log(`assets/voices/LINES.md: ${rows.size} lines, ${Object.keys(by).length} speakers`);
